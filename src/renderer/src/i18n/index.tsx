export type TranslationKey = keyof typeof ZH
export type Translate = (key: TranslationKey, params?: Record<string, string | number>) => string

function interpolate(value: MessageValue | undefined, fallback: MessageValue, params: Record<string, string | number>): string {
  const selected = value ?? fallback
  const rendered = typeof selected === 'function' ? selected(params) : selected
  return rendered.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export function messagesFor(locale: Locale): Messages { return locale === 'en-US' ? EN : ZH }

export function localeLabel(locale: Locale): string {
  return messagesFor(locale)[locale === 'zh-CN' ? 'locale.name.zhCN' : 'locale.name.enUS'] as string
}

interface I18nContextValue { locale: Locale; setLocale: (locale: Locale) => void; t: Translate }
const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children, initialLocale = 'zh-CN' }: { children: ReactNode; initialLocale?: Locale }): ReactNode {
  const [locale, setLocale] = useState<Locale>(initialLocale)
  useEffect(() => { document.documentElement.lang = locale }, [locale])
  const t = useCallback<Translate>((key, params = {}) => interpolate(messagesFor(locale)[key], ZH[key]!, params), [locale])
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (value === null) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
